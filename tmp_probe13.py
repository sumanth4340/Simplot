"""Probe 11 (runs INSIDE Isaac Sim): Y-hinge pre-play USD target + time."""
from pxr import UsdGeom, UsdPhysics, Gf
import numpy as np
import warp as wp
import isaacsim.core.experimental.utils.app as app_utils
import omni.timeline
import omni.usd
from isaacsim.core.experimental.prims import Articulation

stage = omni.usd.get_context().get_stage()
for p in ("/World/YBot", "/World/YGround", "/World/PhysicsScene"):
    o = stage.GetPrimAtPath(p)
    if o and o.IsValid():
        stage.RemovePrim(p)
ps = UsdPhysics.Scene.Define(stage, "/World/PhysicsScene")
ps.CreateGravityDirectionAttr().Set(Gf.Vec3f(0, 0, -1))
ps.CreateGravityMagnitudeAttr().Set(9.81)
g = UsdGeom.Plane.Define(stage, "/World/YGround")
g.CreateWidthAttr().Set(20.0)
g.CreateLengthAttr().Set(20.0)
UsdPhysics.CollisionAPI.Apply(g.GetPrim())
UsdGeom.Xform.Define(stage, "/World/YBot")
base = UsdGeom.Cube.Define(stage, "/World/YBot/Base")
base.GetSizeAttr().Set(1.0)
UsdGeom.Xformable(base.GetPrim()).AddTranslateOp().Set(Gf.Vec3d(0, 0, 0.5))
UsdPhysics.RigidBodyAPI.Apply(base.GetPrim())
UsdPhysics.CollisionAPI.Apply(base.GetPrim())
UsdPhysics.MassAPI.Apply(base.GetPrim()).GetMassAttr().Set(2.0)
UsdPhysics.ArticulationRootAPI.Apply(base.GetPrim())
fx = UsdPhysics.FixedJoint.Define(stage, "/World/YBot/RootFixed")
fx.GetBody0Rel().AddTarget("/World/YBot")
fx.GetBody1Rel().AddTarget("/World/YBot/Base")
fx.GetLocalPos0Attr().Set(Gf.Vec3f(0, 0, 0))
fx.GetLocalRot0Attr().Set(Gf.Quatf(1.0))
fx.GetLocalPos1Attr().Set(Gf.Vec3f(0, 0, -0.5))
fx.GetLocalRot1Attr().Set(Gf.Quatf(1.0))
arm = UsdGeom.Cube.Define(stage, "/World/YBot/Arm")
arm.GetSizeAttr().Set(0.2)
UsdGeom.Xformable(arm.GetPrim()).AddTranslateOp().Set(Gf.Vec3d(0, 0, 1.3))
UsdPhysics.RigidBodyAPI.Apply(arm.GetPrim())
UsdPhysics.CollisionAPI.Apply(arm.GetPrim())
UsdPhysics.MassAPI.Apply(arm.GetPrim()).GetMassAttr().Set(0.5)
j = UsdPhysics.RevoluteJoint.Define(stage, "/World/YBot/Hinge")
j.GetBody0Rel().AddTarget("/World/YBot/Base")
j.GetBody1Rel().AddTarget("/World/YBot/Arm")
j.GetLocalPos0Attr().Set(Gf.Vec3f(0, 0, 0.5))
j.GetLocalRot0Attr().Set(Gf.Quatf(1.0))
j.GetLocalPos1Attr().Set(Gf.Vec3f(0, 0, -0.3))
j.GetLocalRot1Attr().Set(Gf.Quatf(1.0))
j.GetAxisAttr().Set(UsdPhysics.Tokens.y)
d = UsdPhysics.DriveAPI.Apply(j.GetPrim(), "angular")
d.CreateTypeAttr().Set("force")
d.CreateStiffnessAttr().Set(100000.0)
d.CreateDampingAttr().Set(10000.0)
d.CreateMaxForceAttr().Set(1000000.0)
d.CreateTargetPositionAttr().Set(20.0)
print("Y-BUILD-OK")
tl = omni.timeline.get_timeline_interface()
app_utils.stop()
tl.set_current_time(0.0)
await app_utils.update_app_async(steps=5)
t0 = float(tl.get_current_time())
app_utils.play()
await app_utils.update_app_async(steps=5)
robot = Articulation("/World/YBot/Base")
await app_utils.update_app_async(steps=120)
q = robot.get_dof_positions()
q = q.numpy() if isinstance(q, wp.array) else np.asarray(q)
t1 = float(tl.get_current_time())
tl.pause()
print("Y-REPORT q=%s t0=%.3f t1=%.3f dt=%.3f"
      % (np.asarray(q).tolist(), t0, t1, t1 - t0))
